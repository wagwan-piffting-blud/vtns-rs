/// `FUN_10043860`: binary search `SYMBOL_NAMES` by key byte.
pub fn symbol_name_index(key: u8) -> i32 {
    if key == 0 {
        return -1;
    }
    if SYMBOL_NAMES.is_empty() {
        return -1;
    }
    let (mut lo, mut hi): (i32, i32) = (0, SYMBOL_NAMES.len() as i32 - 1);
    loop {
        let mid = (lo + hi) / 2;
        let k = SYMBOL_NAMES[mid as usize].0;
        if k == key {
            return mid;
        }
        if k < key {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
        if lo > hi {
            return -1;
        }
    }
}

